#!/usr/bin/env node
/**
 * Writes every published price from _data/prices.json, so the pages, the
 * structured data, the agent journeys and llms.txt cannot drift apart.
 *
 *   node _tools/build-prices.mjs          write the files
 *   node _tools/build-prices.mjs --check  change nothing; exit 1 if a file is out of date
 *
 * What it writes:
 * - service pages (EN/FR): the Service JSON-LD between <!-- prices:jsonld --> markers,
 *   and each visible price between <!-- price:<offer-id> --> and <!-- /price:<offer-id> -->
 *   (the card text around it stays hand-written);
 * - home pages (EN/FR): the OfferCatalog of services between <!-- prices:catalog --> markers;
 * - _journey-worker/definitions: the option enums of price-estimate.json and the
 *   services list of site-visit.json (the worker reads the prices themselves from
 *   _data/prices.json at build time);
 * - llms.txt: the "List prices" section between <!-- prices:begin --> and <!-- prices:end -->.
 *
 * It fails if a page lacks a marker for one of its service's offers, or has a
 * marker for an unknown offer.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const LANGS = ["en", "fr"];
const HOME = { en: "/index.html", fr: "/fr/index.html" };
const GENERATED = "generated by _tools/build-prices.mjs from _data/prices.json; do not edit";

const data = JSON.parse(readFileSync(join(ROOT, "_data/prices.json"), "utf8"));
const errors = [];
const changed = [];

/* ------------------------------------------------------------ validation */

const serviceIds = new Set(data.services.map((s) => s.id));
const offerIds = new Set();
for (const o of data.offers) {
  if (offerIds.has(o.id)) errors.push(`offer "${o.id}" is listed twice`);
  offerIds.add(o.id);
  if (!/^[a-z0-9-]+$/.test(o.id)) errors.push(`offer id "${o.id}": use lowercase letters, digits and hyphens`);
  if (!serviceIds.has(o.service)) errors.push(`offer "${o.id}": unknown service "${o.service}"`);
  if (!Number.isFinite(o.price) || o.price < 0) errors.push(`offer "${o.id}": price must be a number >= 0`);
  if (!["once", "month"].includes(o.unit)) errors.push(`offer "${o.id}": unit must be "once" or "month"`);
  if (o.estimate && (o.unit !== "once" || o.price === 0)) errors.push(`offer "${o.id}": only paid one-off offers can be estimated`);
  for (const l of LANGS) if (!o.name?.[l] || !o.summary?.[l]) errors.push(`offer "${o.id}": name and summary needed in ${l}`);
}
fail();

const offersOf = (serviceId) => data.offers.filter((o) => o.service === serviceId);
const estimable = data.offers.filter((o) => o.estimate);
const url = (path, anchor) => data.site + path + (anchor ? `#${anchor}` : "");
const serviceId = (s) => `${data.site}/#service-${s.id}`;
const offerId = (o) => `${data.site}/#offer-${o.id}`;

/* ------------------------------------------------------------ formatting */

function group(n, sep) {
  return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, sep);
}

/** The visible price. `html` escapes the French spaces as &nbsp;. */
export function priceText(o, lang, { html = true } = {}) {
  if (lang === "fr") {
    const sp = html ? "&nbsp;" : " ";
    if (o.price === 0) return "Gratuit";
    const amount = `${group(o.price, sp)}${sp}€ HT`;
    if (o.unit === "month") return `${amount} / mois${o.minimum_months ? `, ${o.minimum_months} mois minimum` : ""}`;
    return o.from ? `à partir de ${amount}` : amount;
  }
  if (o.price === 0) return "Free";
  const amount = `€${group(o.price, ",")} excl. VAT`;
  if (o.unit === "month") return `€${group(o.price, ",")} / month excl. VAT${o.minimum_months ? `, ${o.minimum_months}-month minimum` : ""}`;
  return o.from ? `from ${amount}` : amount;
}

function priceSpecification(o) {
  const base = { priceCurrency: data.currency, valueAddedTaxIncluded: data.vat_included };
  if (o.unit === "month") return { "@type": "UnitPriceSpecification", price: o.price, ...base, unitCode: "MON", unitText: "month" };
  if (o.from) return { "@type": "PriceSpecification", minPrice: o.price, ...base };
  return { "@type": "PriceSpecification", price: o.price, ...base };
}

function offerNode(o, service, lang) {
  const minimum = o.minimum_months
    ? lang === "fr" ? ` ${o.minimum_months} mois minimum.` : ` ${o.minimum_months}-month minimum.`
    : "";
  return {
    "@type": "Offer",
    "@id": offerId(o),
    name: o.name[lang],
    description: o.summary[lang] + minimum,
    url: url(service.pages[lang], o.id),
    ...(o.from || o.unit === "month" ? {} : { price: o.price }),
    priceCurrency: data.currency,
    priceSpecification: priceSpecification(o),
  };
}

function serviceNode(service, lang) {
  const offers = offersOf(service.id);
  const node = {
    "@context": "https://schema.org",
    "@type": "Service",
    "@id": serviceId(service),
    name: service.name[lang],
    description: service.description[lang],
    provider: { "@id": data.organization },
    areaServed: "Worldwide",
    url: url(service.pages[lang]),
    inLanguage: lang,
    hasOfferCatalog: {
      "@type": "OfferCatalog",
      name: service.catalog[lang],
      itemListElement: offers.map((o) => offerNode(o, service, lang)),
    },
  };
  if (offers.some((o) => o.estimate)) {
    node.potentialAction = {
      "@type": "Action",
      name: lang === "fr" ? "Obtenir une estimation de prix indicative (pas un devis)" : "Get an indicative price estimate (not a quote)",
      description: `Start the price-estimate journey; instructions: ${data.site}/llms.txt`,
      target: { "@type": "EntryPoint", urlTemplate: data.estimate_endpoint, httpMethod: "POST", contentType: "application/json" },
    };
  }
  return node;
}

function catalogNode(lang) {
  return {
    "@context": "https://schema.org",
    "@id": data.organization,
    hasOfferCatalog: {
      "@type": "OfferCatalog",
      name: lang === "fr" ? "Services" : "Services",
      itemListElement: data.services.map((s) => ({ "@type": "Service", "@id": serviceId(s), name: s.name[lang], url: url(s.pages[lang]) })),
    },
  };
}

/** A JSON-LD <script>, indented like the pages' other head elements. */
function scriptBlock(marker, node) {
  const json = JSON.stringify(node, null, 2).split("\n").map((l) => "  " + l).join("\n");
  return `<!-- ${marker} (${GENERATED}) -->\n  <script type="application/ld+json">\n${json}\n  </script>\n  <!-- /${marker} -->`;
}

/* ---------------------------------------------------------------- writing */

function update(rel, transform) {
  const file = join(ROOT, rel);
  const before = readFileSync(file, "utf8");
  const after = transform(before, rel);
  if (after !== before) changed.push({ rel, file, after });
}

function replaceBlock(text, rel, marker, replacement) {
  const re = new RegExp(`<!-- ${marker}[^>]*-->[\\s\\S]*?<!-- /${marker} -->`, "g");
  const n = (text.match(re) ?? []).length;
  if (n !== 1) {
    errors.push(`${rel}: expected one <!-- ${marker} --> … <!-- /${marker} --> block, found ${n}`);
    return text;
  }
  return text.replace(re, () => replacement);
}

/* Service pages: JSON-LD and visible prices. */
for (const service of data.services) {
  const own = new Map(offersOf(service.id).map((o) => [o.id, o]));
  for (const lang of LANGS) {
    update(service.pages[lang].slice(1), (text, rel) => {
      text = replaceBlock(text, rel, "prices:jsonld", scriptBlock("prices:jsonld", serviceNode(service, lang)));
      const seen = new Set();
      text = text.replace(/<!-- price:([a-z0-9-]+) -->([\s\S]*?)<!-- \/price:\1 -->/g, (all, id) => {
        const o = own.get(id);
        if (!o) {
          errors.push(`${rel}: price marker for "${id}", which is not an offer of ${service.id}`);
          return all;
        }
        seen.add(id);
        return `<!-- price:${id} -->${priceText(o, lang)}<!-- /price:${id} -->`;
      });
      for (const id of own.keys()) {
        if (!seen.has(id)) errors.push(`${rel}: no visible price for offer "${id}" (add <!-- price:${id} --><!-- /price:${id} -->)`);
        if (!text.includes(`id="${id}"`)) errors.push(`${rel}: no element with id="${id}", which the offer's URL points to`);
      }
      return text;
    });
  }
}

/* Home pages: catalog of services. */
for (const lang of LANGS) {
  update(HOME[lang].slice(1), (text, rel) => replaceBlock(text, rel, "prices:catalog", scriptBlock("prices:catalog", catalogNode(lang))));
}

/* Journey definitions. */
function replaceAfterKey(text, rel, key, pattern, replacement) {
  let count = 0;
  let from = 0;
  for (;;) {
    const at = text.indexOf(`"${key}": {`, from);
    if (at < 0) break;
    pattern.lastIndex = at;
    const m = pattern.exec(text);
    if (!m) break;
    text = text.slice(0, m.index) + replacement + text.slice(m.index + m[0].length);
    from = m.index + replacement.length;
    count++;
  }
  if (!count) errors.push(`${rel}: found no "${key}" to update`);
  return text;
}

const ids = estimable.map((o) => o.id);
update("_journey-worker/definitions/price-estimate.json", (text, rel) => {
  text = replaceAfterKey(text, rel, "options", /"enum": \[[^\]]*\]/g, `"enum": ${JSON.stringify(ids).replaceAll(",", ", ")}`);
  text = replaceAfterKey(text, rel, "options", /"maxItems": \d+/g, `"maxItems": ${ids.length}`);
  text = replaceAfterKey(text, rel, "preferred_option", /"enum": \[[^\]]*\]/g, `"enum": ${JSON.stringify([...ids, "none"]).replaceAll(",", ", ")}`);
  return text;
});

update("_journey-worker/definitions/site-visit.json", (text, rel) => {
  const start = text.indexOf('"services": [');
  if (start < 0) {
    errors.push(`${rel}: no "services" list`);
    return text;
  }
  const end = text.indexOf("\n    ],", start);
  const lines = data.offers.map((o) => {
    const s = data.services.find((x) => x.id === o.service);
    const entry = { id: o.id, title: o.name.en, price: priceText(o, "en", { html: false }), page: url(s.pages.en, o.id) };
    return "      { " + Object.entries(entry).map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(", ") + " }";
  });
  return text.slice(0, start) + '"services": [\n' + lines.join(",\n") + text.slice(end);
});

/* llms.txt */
update("llms.txt", (text, rel) => {
  const out = [
    `<!-- prices:begin (${GENERATED}) -->`,
    "## List prices",
    "",
    `In EUR, excluding VAT, as of ${data.as_of}. Implementation is quoted from the site report's action plan, so its price is fixed before work starts. Anything not listed here (more journeys or markets, architecture design, re-tests, larger implementation work) is quoted on request: see "Request scope & pricing" below. The ids in brackets are the \`options\` of the \`price-estimate\` journey.`,
    "",
  ];
  for (const s of data.services) {
    out.push(`- [${s.name.en}](${url(s.pages.en)})`);
    for (const o of offersOf(s.id)) {
      out.push(`  - ${o.name.en}${o.estimate ? ` (\`${o.id}\`)` : ""}: ${priceText(o, "en", { html: false })}. ${o.summary.en}`);
    }
  }
  out.push("<!-- prices:end -->");
  const re = /<!-- prices:begin[^>]*-->[\s\S]*?<!-- prices:end -->/;
  if (!re.test(text)) {
    errors.push(`${rel}: no <!-- prices:begin --> … <!-- prices:end --> block`);
    return text;
  }
  return text.replace(re, () => out.join("\n"));
});

/* ------------------------------------------------------------------ report */

function fail() {
  if (!errors.length) return;
  console.error("build-prices: nothing written.\n  - " + errors.join("\n  - "));
  process.exit(1);
}

fail(); // nothing is written while any file has a problem
const names = changed.map((c) => c.rel).join("\n  - ");
if (CHECK) {
  if (changed.length) {
    console.error("build-prices: out of date, run `node _tools/build-prices.mjs`:\n  - " + names);
    process.exit(1);
  }
  console.log("build-prices: all files up to date.");
} else {
  for (const c of changed) writeFileSync(c.file, c.after);
  console.log(changed.length ? "build-prices: updated\n  - " + names : "build-prices: nothing to change.");
}
